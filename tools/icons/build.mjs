// npm pack @phosphor-icons/core@2.1.1; unpack into design/.phosphor/package, then run this file.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { ICONS } from './icons.mjs';
const root = new URL('../../', import.meta.url);
const source = new URL('design/.phosphor/package/', root);
const target = new URL('app/src/main/res/drawable/', root);
mkdirSync(target, { recursive: true });
const entries = [];
for (const [alias, name] of Object.entries(ICONS)) {
  for (const weight of ['regular', ...(['bike', 'route', 'wrench', 'doc'].includes(alias) ? ['fill'] : [])]) {
    const svg = readFileSync(new URL(`assets/${weight}/${name}${weight === 'fill' ? '-fill' : ''}.svg`, source), 'utf8');
    if (/<(circle|rect|polygon|g)\b/.test(svg)) throw Error(`Unsupported SVG element: ${name}`);
    const paths = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"[^>]*\/?\s*>/g)].map(m => m[1]);
    if (!paths.length) throw Error(`No paths: ${name}`);
    const id = `ph_${alias.replaceAll('-', '_')}${weight === 'fill' ? '_fill' : ''}`;
    writeFileSync(new URL(`${id}.xml`, target), `<?xml version="1.0" encoding="utf-8"?>\n<!-- Phosphor Icons, MIT; generated by tools/icons/build.mjs. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="256" android:viewportHeight="256">\n${paths.map(d => `    <path android:fillColor="#FF000000" android:pathData="${d}" />`).join('\n')}\n</vector>\n`);
    entries.push(`    "${alias}${weight === 'fill' ? '-fill' : ''}" to R.drawable.${id},`);
  }
}
writeFileSync(new URL('app/src/main/java/com/kaze/motoplus/ui/Icons.kt', root), `package com.kaze.motoplus.ui\n\nimport com.kaze.motoplus.R\n\n// Generated by tools/icons/build.mjs; Phosphor Icons (MIT).\nval ICONS = mapOf(\n${entries.join('\n')}\n)\n`);
copyFileSync(new URL('LICENSE', source), new URL('tools/icons/LICENSE', root));
copyFileSync(new URL('LICENSE', source), new URL('app/src/main/assets/licenses/Phosphor-MIT.txt', root));
console.log(`${entries.length} Phosphor vector drawables`);
