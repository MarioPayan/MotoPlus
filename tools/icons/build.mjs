// Turns tools/icons/icons.mjs into app/src/main/java/com/kaze/motoplus/ui/Icons.kt: one SVG path string per icon.
// Run: node tools/icons/build.mjs
import { writeFileSync } from 'node:fs';
import { ICONS } from './icons.mjs';

const f = n => +(+n).toFixed(2);
const attrs = tag => Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map(m => [m[1], m[2]]));
function rect({ x, y, width: w, height: h, rx = 0 }) {
  [x, y, w, h, rx] = [x, y, w, h, rx].map(Number);
  if (!rx) return `M${x} ${y}h${w}v${h}h${-w}z`;
  return `M${f(x + rx)} ${y}h${f(w - 2 * rx)}a${rx} ${rx} 0 0 1 ${rx} ${rx}v${f(h - 2 * rx)}a${rx} ${rx} 0 0 1 ${-rx} ${rx}h${f(2 * rx - w)}a${rx} ${rx} 0 0 1 ${-rx} ${-rx}v${f(2 * rx - h)}a${rx} ${rx} 0 0 1 ${rx} ${-rx}z`;
}
const circle = ({ cx, cy, r }) => { [cx, cy, r] = [cx, cy, r].map(Number); return `M${f(cx - r)} ${cy}a${r} ${r} 0 1 0 ${f(2 * r)} 0a${r} ${r} 0 1 0 ${f(-2 * r)} 0z`; };

const out = Object.entries(ICONS).map(([name, svg]) => {
  const d = [...svg.matchAll(/<(path|rect|circle)\b([^>]*)\/>/g)].map(([, kind, a]) => {
    const at = attrs(a);
    if (at['stroke-dasharray']) throw new Error(`${name}: dashed strokes are not supported`);
    return kind === 'path' ? at.d : kind === 'rect' ? rect(at) : circle(at);
  }).join(' ');
  // A few icons use a heavier stroke for one element; those become a second path drawn at that width.
  const heavy = [...svg.matchAll(/<path d="([^"]*)" stroke-width="([\d.]+)"\/>/g)].map(m => [m[1], m[2]]);
  if (heavy.length) return `    "${name}" to Glyph("${d.replace(heavy[0][0], '').trim()}", "${heavy[0][0]}", ${heavy[0][1]}f),`;
  return `    "${name}" to Glyph("${d}"),`;
});

writeFileSync(new URL('../../app/src/main/java/com/kaze/motoplus/ui/Icons.kt', import.meta.url), `package com.kaze.motoplus.ui

// Generated by tools/icons/build.mjs from tools/icons/icons.mjs. Do not edit by hand.

/** A line icon on a 24 × 24 grid; [heavy] is an optional second path drawn with [heavyWidth]. */
class Glyph(val d: String, val heavy: String? = null, val heavyWidth: Float = 0f)

val GLYPHS: Map<String, Glyph> = mapOf(
${out.join('\n')}
)
`);
console.log(`${out.length} icons`);
